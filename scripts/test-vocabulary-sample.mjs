import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
try {
  for (const width of [375, 430, 1280]) {
    const page = await browser.newPage({ viewport: { width, height: 932 } });
    const errors = [];
    let apiCalls = 0;
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (request.url().includes('/api/chat')) apiCalls++; });
    await page.goto('http://127.0.0.1:4177/');
    await page.click('#openNce1Btn');
    await page.click('.lesson-card[data-id="lesson-41"]');
    const learning = await page.evaluate(() => localStorage.getItem('nce_learning_records_v1'));
    await page.click('#vocabEntry');
    await page.waitForSelector('#vocabListView.active');
    assert.match(await page.locator('#vocabListView').textContent(), /暂无生词/);
    assert.equal(await page.locator('dialog.vocab-dialog').count(), 0);
    await page.click('#homeBtn');
    await page.locator('[data-analysis]').first().click();
    await page.locator('#analysisContent .understanding-word-details summary').click();
    await page.locator('.vocab-word-toggle').nth(3).click();
    assert.equal(await page.locator('.vocab-word-toggle').nth(3).textContent(), '已收藏');
    await page.click('#homeBtn');
    await page.click('#vocabEntry');
    await page.screenshot({ path: `reports/vocabulary-list-${width}.png` });
    await page.click('#vocabStart');
    await page.waitForSelector('#vocabPracticeView.active');
    assert.equal(await page.locator('.handwriting-root, .handwriting-modes, .handwriting-pad').count(), 0);
    await page.fill('.vocab-input', 'draft');
    await page.click('#vocabAnswer');
    assert.equal(await page.locator('.vocab-input').inputValue(), 'heavy');
    assert.match(await page.locator('#vocabAnswer').textContent(), /隐藏答案/);
    await page.click('#vocabAnswer');
    assert.equal(await page.locator('.vocab-input').inputValue(), 'draft');
    assert.equal(await page.locator('.vocab-input').isEnabled(), true);
    assert.match(await page.locator('#vocabAnswer').textContent(), /显示答案/);
    assert.equal(await page.locator('#vocabPracticeView .chinese').textContent(), '重的');
    assert.ok(!(await page.locator('#vocabPracticeView').textContent()).includes('heavy'));
    await page.screenshot({ path: `reports/vocabulary-practice-${width}.png` });
    await page.click('#vocabPause');
    assert.match(await page.locator('#vocabPracticeView').textContent(), /练习已暂停/);
    await page.keyboard.press('Enter');
    await page.fill('.vocab-input', 'wrong');
    await page.keyboard.press('Space');
    assert.equal(await page.locator('.vocab-input').getAttribute('aria-invalid'), 'true');
    assert.equal(await page.locator('.vocab-input').inputValue(), 'wrong');
    assert.ok(!(await page.locator('#vocabPracticeView').textContent()).includes('heavy'));
    await page.fill('.vocab-input', 'HEAVY');
    await page.keyboard.press('Space');
    assert.match(await page.locator('#vocabPracticeView .feedback').textContent(), /正确/);
    await page.keyboard.press('Enter');
    assert.match(await page.locator('#vocabPracticeView').textContent(), /本轮完成/);
    assert.match(await page.locator('#vocabPracticeView').textContent(), /正确率 0%/);
    await page.click('#vocabRetry');
    await page.keyboard.press('Alt');
    assert.equal(await page.locator('.vocab-input').inputValue(), 'heavy');
    await page.click('#vocabNext');
    await page.click('#vocabBack');
    await page.click('#homeBtn');
    assert.equal(await page.evaluate(() => localStorage.getItem('nce_learning_records_v1')), learning);
    await page.reload();
    await page.click('#openNce1Btn');
    await page.click('.lesson-card[data-id="lesson-41"]');
    assert.match(await page.locator('#vocabEntry').textContent(), /1/);
    await page.click('#vocabEntry');
    await page.locator('[data-remove]').click();
    assert.match(await page.locator('#vocabListView').textContent(), /暂无生词/);
    await page.click('#homeBtn');
    await page.click('#startBtn');
    await page.evaluate(async () => {
      state.current.wrongIndexes = [3]; state.phase = 'wrong';
      await window.offerVocabularyMistakes();
    });
    await page.click('#vocabCollect');
    const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('yuke_vocabulary_v1:nce1:lesson-41')));
    assert.equal(saved.length, 1);
    assert.equal(saved[0].text.toLowerCase(), 'heavy');
    assert.equal(apiCalls, 0);
    assert.deepEqual(errors, []);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    console.log(`${width}px: collection, hidden answer, retry, persistence, removal, mistake collection and unchanged learning records passed.`);
    await page.close();
  }
} finally { await browser.close(); }
